-- Generate the theme-driven view pages from data/themes.yml (Quarto pre-render).
--
-- Quarto listings sort and filter on page metadata natively, but they can't
-- group a listing or make one page per data item (see ADR-0002). So this
-- writes, before every full render or preview:
--
--   path.qmd            the Path view: one section per theme in path order,
--                       each a native listing filtered to that theme
--   themes/<slug>.qmd   one Theme view per theme: a native listing of every
--                       page of that theme, any type
--   themes/index.qmd    an index of the Theme views
--
-- The generated files are build output (gitignored): edit this script or
-- data/themes.yml, never the generated pages. Lua (run by `quarto run`, i.e.
-- pandoc's Lua) keeps rendering free of Python, like filters/page-layout.lua.

local CONTENT_FOLDERS = { "topics", "dictionary", "essays", "prototypes", "tools" }
local HEADER = "# Generated by scripts/views.lua from data/themes.yml. Do not edit.\n"

local root = os.getenv("QUARTO_PROJECT_DIR") or "."

local function read_file(path)
  local f = assert(io.open(path, "r"), "views: cannot read " .. path)
  local text = f:read("a")
  f:close()
  return text
end

local function write_file(path, text)
  local f = assert(io.open(path, "w"), "views: cannot write " .. path)
  f:write(text)
  f:close()
end

-- data/themes.yml is a YAML list; parse it with pandoc by wrapping it as front
-- matter under a `themes` key (as filters/page-layout.lua does). Path order.
local function load_themes()
  local text = read_file(root .. "/data/themes.yml")
  local indented = text:gsub("([^\n]*)", "  %1")
  local doc = pandoc.read("---\nthemes:\n" .. indented .. "\n---\n", "markdown")
  local themes = {}
  for _, t in ipairs(doc.meta.themes) do
    local stage = t.stage and pandoc.utils.stringify(t.stage) or ""
    table.insert(themes, {
      slug = pandoc.utils.stringify(t.slug),
      title = pandoc.utils.stringify(t.title),
      stage = stage,
    })
  end
  return themes
end

local function stage_label(theme)
  if theme.stage ~= "" then return "Stage " .. theme.stage end
  return "Alongside the path"
end

local function yaml_string(s)
  return '"' .. s:gsub('\\', '\\\\'):gsub('"', '\\"') .. '"'
end

-- A native listing of every page of one theme, alphabetical by title.
-- `prefix` makes the content globs relative to the view page.
local function theme_listing(id, slug, prefix, fields)
  local out = { "  - id: " .. id, "    contents:" }
  for _, folder in ipairs(CONTENT_FOLDERS) do
    for _, ext in ipairs({ "qmd", "md" }) do
      table.insert(out, '      - "' .. prefix .. folder .. "/*." .. ext .. '"')
    end
  end
  for _, line in ipairs({
    "    include:", "      theme: " .. slug,
    "    type: table", "    sort: title", "    fields: " .. fields,
    "    field-display-names:", '      lens: "Lens"', '      maturity: "Maturity"',
    "    sort-ui: false", "    filter-ui: false",
  }) do
    table.insert(out, line)
  end
  return table.concat(out, "\n") .. "\n"
end

local function path_page(themes)
  local listings, sections = {}, {}
  for _, t in ipairs(themes) do
    table.insert(listings, theme_listing("path-" .. t.slug, t.slug, "", "[title, type, maturity]"))
    table.insert(sections, string.format(
      "## %s: [%s](themes/%s.qmd)\n\n::: {#path-%s}\n:::\n",
      stage_label(t), t.title, t.slug, t.slug))
  end
  return "---\n" .. HEADER .. 'title: "Path"\nlisting:\n' .. table.concat(listings)
    .. "---\n\n"
    .. "The default order I'm learning in: one stage per theme. Themes without a\n"
    .. "stage come last; I learn them alongside the others.\n\n"
    .. table.concat(sections, "\n")
end

local function theme_page(t)
  local where
  if t.stage ~= "" then
    where = "Stage " .. t.stage .. " of the [path](../path.qmd)."
  else
    where = "A theme without a stage, learned alongside the [path](../path.qmd)."
  end
  return "---\n" .. HEADER .. "title: " .. yaml_string(t.title) .. "\nlisting:\n"
    .. theme_listing("theme", t.slug, "../", "[title, type, lens, maturity]")
    .. "---\n\n" .. where .. " Every page of this theme, of any type.\n\n"
    .. "::: {#theme}\n:::\n"
end

local function themes_index(themes)
  local items = {}
  for _, t in ipairs(themes) do
    table.insert(items, string.format("- %s: [%s](%s.qmd)", stage_label(t), t.title, t.slug))
  end
  return "---\n" .. HEADER .. 'title: "Themes"\n---\n\n'
    .. "One page per theme, in path order.\n\n" .. table.concat(items, "\n") .. "\n"
end

local themes = load_themes()
write_file(root .. "/path.qmd", path_page(themes))

local dir = root .. "/themes"
pandoc.system.make_directory(dir, true)
for _, name in ipairs(pandoc.system.list_directory(dir)) do
  os.remove(dir .. "/" .. name) -- drop pages of removed themes
end
write_file(dir .. "/index.qmd", themes_index(themes))
for _, t in ipairs(themes) do
  write_file(dir .. "/" .. t.slug .. ".qmd", theme_page(t))
end
